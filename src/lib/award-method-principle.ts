/**
 * 決標原則（採購法第 52 條）：更正「逾某金額一律最低標」之常見誤解。
 * 第 52 條係四原則擇一載明於招標文件；並有最有利標、複數決標等其他情境。
 */

export function isAwardMethodPrincipleQuery(query: string): boolean {
  const q = query.replace(/\s+/g, "");
  if (!q) return false;

  // 減價／比減／超底價等屬決標後程序，非「應採哪一種決標原則」
  if (
    /減價|比減|超過底價|超底價|議價次數|偏低/.test(q) &&
    !/決標原則|最有利標|第52條|第五十二條|一律最低標|應依最低標/.test(q)
  ) {
    return false;
  }

  const amountForcesLowest =
    /(100萬|一百萬|150萬|公告金額以上|達公告金額|查核金額以上|巨額)/.test(q) &&
    /最低標/.test(q) &&
    /(應依|應採|必須|一律|一定|原則辦理|只能|要不要|是否)/.test(q);

  const art52Award =
    /(第52條|第五十二條)/.test(q) &&
    /(決標|最低標|最有利標|原則)/.test(q);

  const compare =
    /決標原則/.test(q) || (/最低標/.test(q) && /最有利標/.test(q));

  const mustLowestClaim =
    /一律.*最低標|應依最低標原則|必須.*最低標|只能.*最低標|應採最低標/.test(q);

  return amountForcesLowest || art52Award || compare || mustLowestClaim;
}

/** 查詢擴展：強化第 52 條、最有利標脈絡檢索 */
export function awardMethodExpansionTerms(query: string): string[] {
  if (!isAwardMethodPrincipleQuery(query)) return [];
  return [
    "第五十二條",
    "第52條",
    "決標原則",
    "最低標",
    "最有利標",
    "不訂底價",
    "複數決標",
    "專業服務",
    "技術服務",
    "資訊服務",
  ];
}

