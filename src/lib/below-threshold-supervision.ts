/**
 * 未達公告金額採購之監辦門檻（中央機關未達公告金額採購監辦辦法）。
 * 勿與公告金額以上之「會同監辦」規定混淆。
 */

export function isBelowThresholdSupervisionQuery(query: string): boolean {
  const q = query.trim();
  if (!q) return false;
  const below = /未達公告|小額採購|公告金額十分之一/.test(q);
  const supervision = /監辦|會同監辦|派員監辦|通知.*監辦|什麼時候.*監辦|何時.*監辦/.test(q);
  return below && supervision;
}

